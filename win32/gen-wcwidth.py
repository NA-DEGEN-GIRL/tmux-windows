#!/usr/bin/env python3
#
# Generate win32/win32-wcwidth.h from the Unicode Character Database.
#
# Usage: gen-wcwidth.py UCD-DIR > win32/win32-wcwidth.h
#
# UCD-DIR must contain EastAsianWidth.txt, DerivedGeneralCategory.txt and
# PropList.txt from https://www.unicode.org/Public/UCD/latest/ucd/.
#
# Width rules (matching glibc and Windows Terminal):
#  - general categories Mn, Me and Cf are zero width, except U+00AD SOFT
#    HYPHEN and the prepended concatenation marks which are visible;
#  - Hangul Jamo medial vowels and final consonants (U+1160-U+11FF and
#    U+D7B0-U+D7FF) and the Hangul tone marks (U+302E-U+302F) are zero
#    width, they combine with the preceding character;
#  - East_Asian_Width W and F are double width, as is all of Hangul Jamo
#    Extended-A (U+A960-U+A97F);
#  - everything else (including private use and ambiguous) is single width.

import os
import re
import sys

def ranges(path, want):
    out = []
    version = None
    with open(path, encoding='utf-8') as f:
        for line in f:
            if version is None:
                m = re.match(r'#\s*\S+-(\d+\.\d+\.\d+)\.txt', line)
                if m:
                    version = m.group(1)
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            cps, value = [x.strip() for x in line.split(';')[:2]]
            if value not in want:
                continue
            if '..' in cps:
                a, b = cps.split('..')
            else:
                a = b = cps
            out.append((int(a, 16), int(b, 16)))
    return out, version

def to_set(rs):
    s = set()
    for a, b in rs:
        s.update(range(a, b + 1))
    return s

def merge(s):
    out = []
    for cp in sorted(s):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out

def emit(name, rs):
    print('static const struct win32_wcwidth_range %s[] = {' % name)
    for a, b in rs:
        print('\t{ 0x%05X, 0x%05X },' % (a, b))
    print('};')

def main():
    d = sys.argv[1]
    gc, version = ranges(os.path.join(d, 'DerivedGeneralCategory.txt'),
        ('Mn', 'Me', 'Cf'))
    pcm, _ = ranges(os.path.join(d, 'PropList.txt'),
        ('Prepended_Concatenation_Mark',))
    eaw, eaw_version = ranges(os.path.join(d, 'EastAsianWidth.txt'),
        ('W', 'F'))

    zero = to_set(gc) - to_set(pcm) - {0x00AD}
    zero |= set(range(0x1160, 0x1200)) | set(range(0xD7B0, 0xD800))
    zero |= {0x302E, 0x302F}

    wide = to_set(eaw) | set(range(0xA960, 0xA980))
    wide -= zero

    print('/* Generated by win32/gen-wcwidth.py from Unicode %s data. */' %
        version)
    print('/* Do not edit: rerun the generator instead. */')
    print()
    emit('win32_wcwidth_zero', merge(zero))
    print()
    emit('win32_wcwidth_wide', merge(wide))

main()
